// groceryLexicon.ts — كلام المقاضي بلهجة كل سوق (ZAD_PLAN ٤.٢٥، طلب المالك ٨/١١).
//
// «عروض المقاضي» و«عروض خزين البيت» معناها العروض كلها، مش صنف اسمه «مقاضي».
// قبل كده الكلمة كانت بتدخل فلتر الصنف فيرجع مفيش عروض، وعرض الصبح كان بيدوّر
// على «مقاضي» زي أي صنف في القايمة.
//
// بيانات مطابقة مع كلام العميل وقايمة الشرا: ممنوع تترجم (قاعدة i18n في CLAUDE.md).
// «طلبات» لوحدها مش هنا بالقصد: دي تطبيق طلبات، و«عروض طلبات» معناها عروض التطبيق.

const EGYPT = ["طلبات البيت", "طلبات الشهر", "طلبات السوبرماركت", "خزين", "خزين البيت", "خزين الشهر", "تموين", "تموين البيت", "حاجات البيت", "لوازم البيت"];
const SAUDI = ["مقاضي", "مقاضي البيت", "مقاضي الشهر", "اغراض البيت", "اغراض السوبرماركت", "مواد غذائيه"];
const SHARED = ["سوبرماركت", "بقاله"];

/** نفس تطبيع الأسامي: الهمزات والتاء المربوطة و«ال» أول كل كلمة. */
function key(text: string): string {
  return text.trim().toLowerCase()
    .replace(/[ً-ٰٟ]/g, "")
    .replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي")
    .split(/\s+/).filter((w) => w !== "")
    .map((w) => (w.startsWith("ال") && w.length > 2 ? w.slice(2) : w))
    .join(" ");
}

const TERMS = new Set([...EGYPT, ...SAUDI, ...SHARED].map(key));

/** [text] كله كلمة عامة للمقاضي، مش اسم صنف. */
export function isGroceryTerm(text: string | null | undefined): boolean {
  return TERMS.has(key(String(text ?? "")));
}
