import { assert, assertEquals } from "jsr:@std/assert@1";
import { expectedSpeechSeconds, runawayLimitSeconds, trimRunawaySpeech, TTS_SAMPLE_RATE } from "./ttsTrim.ts";

const SR = TTS_SAMPLE_RATE;

/** Synthetic PCM: [seconds, loud?] segments — a 220 Hz tone for speech, near-silence for pauses. */
function clip(segments: Array<[number, boolean]>): Uint8Array<ArrayBuffer> {
  const total = segments.reduce((n, [s]) => n + Math.round(s * SR), 0);
  const out = new Int16Array(total);
  let i = 0;
  for (const [s, loud] of segments) {
    const n = Math.round(s * SR);
    for (let k = 0; k < n; k++, i++) out[i] = loud ? Math.round(8000 * Math.sin((2 * Math.PI * 220 * i) / SR)) : (k % 7) - 3;
  }
  return new Uint8Array(out.buffer);
}

const secondsOf = (pcm: Uint8Array<ArrayBuffer>) => pcm.byteLength / 2 / SR;

const TEXT = "صباح الخير يا قمر، متنساش تفطر وتاخد دواك"; // 8 words → expected 5 s, limit 7.5 s

Deno.test("the budget: two words a second plus a breath, and 1.3× plus a second before it is a runaway", () => {
  assertEquals(expectedSpeechSeconds(TEXT), 5);
  assertEquals(runawayLimitSeconds(TEXT), 7.5);
  // One word: 1.5 s expected, a runaway past 2.95 s.
  assertEquals(runawayLimitSeconds("تمام"), 2.95);
  assertEquals(expectedSpeechSeconds("  ⏰  "), 1);
});

Deno.test("a clip of normal length comes back untouched", () => {
  const pcm = clip([[2, true], [0.5, false], [2.5, true], [0.3, false], [1.5, false]]);
  assertEquals(trimRunawaySpeech(pcm, TEXT), pcm);
});

Deno.test("a runaway tail after a pause is cut at that pause (the «speech generated by…» case)", () => {
  // 5 s of the text, a 0.6 s pause, then 6 s of words nobody wrote.
  const pcm = clip([[2.4, true], [0.2, false], [2.4, true], [0.6, false], [6, true]]);
  const out = trimRunawaySpeech(pcm, TEXT);
  const s = secondsOf(out);
  assert(s >= 5 && s <= 5.1, `cut at ${s}s`);
});

Deno.test("a short breath inside the text is not taken for the end", () => {
  // A 0.2 s breath at 4.2 s (after 80% of the expected 5 s) is shorter than a pause.
  const pcm = clip([[4.2, true], [0.2, false], [1, true], [0.8, false], [6, true]]);
  const s = secondsOf(trimRunawaySpeech(pcm, TEXT));
  assert(s >= 5.4 && s <= 5.5, `cut at ${s}s`);
});

Deno.test("noise with no pause at all ends at the limit, faded", () => {
  const pcm = clip([[14, true]]);
  const out = trimRunawaySpeech(pcm, TEXT);
  assertEquals(secondsOf(out), 7.5);
  const samples = new Int16Array(out.buffer);
  assertEquals(samples[samples.length - 1], 0);
});

Deno.test("a one-word reply with a sentence tacked on after a pause loses the sentence", () => {
  const pcm = clip([[0.7, true], [0.5, false], [2.5, true]]);
  const s = secondsOf(trimRunawaySpeech(pcm, "تمام"));
  assert(s >= 0.7 && s <= 0.75, `cut at ${s}s`);
});
