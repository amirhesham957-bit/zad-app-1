// forcedLog.ts — رسالة فلوس واضحة والموديل رد بكلام من غير ما يقترح التسجيل (ZAD_PLAN ٣.٣).
//
// التقييم الليلي ٢٧/١٠: ١٧ من ٢٠ حالة فشل كانوا «سجّل»: «حلاقة 80»، «قهوة وكرواسون ب 135»، «قبضت المرتب 18000» —
// موديل الوكيل (lite) رد «تبي أسجلها؟» أو «أبشر، بصرف 92 ريال حق أوبر»، أو ادّعى إنه سجّل فالحارس بدّل رده بـ«لسه
// ماعملتش ده». ونفس الحالة في فحص ما بعد النشر («صرفت 50 جنيه قهوة»، #318، #319، #320). السؤال «تبي أسجلها؟» زيادة:
// اقتراح log_transaction هو نفسه كارت «أكّد؟» — مفيش حاجة بتتسجل من غير موافقته.
//
// القاعدة هنا ثابتة ومن غير موديل: الرسالة فيها مبلغ، ومش سؤال، ومش تحويل أو نصب أو قرض أو التزام أو مسح، وفيها فعل
// صرف/قبض أو الرد نفسه بيعرض التسجيل. لو آه ⇒ محاولة واحدة بأداة log_transaction بس وإجبار النداء.

import { SILENT_WRITE_TOOLS } from "./receipts.ts";

const normalize = (text: string) =>
  text.replace(/[\u064B-\u065F\u0670\u0640]/g, "").replace(/[أإآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه").toLowerCase();

/** مبلغ: رقم بأي أرقام، أو «ألف/ألفين/مليون». */
const AMOUNT = /[0-9٠-٩]|(^|\s)(الف|الفين|مليون)(\s|$)/;
/** فعل صرف أو قبض صريح، أو أمر تسجيل («اه سجلي يا زاد ٣٠٠ جنيه خضار» — التقييم ٣/١١، جروك رد «صرفت … صح؟»). */
const MONEY_VERB = /(^|\s)(صرفت|دفعت|سددت|اشتريت|جبت|طلبت|عبيت|تسوقت|اتعشينا|اتغدينا|قبضت|دخلي|جالي|نزلي|استلمت|سجل|سجلي|سجللي|سجلهالي|sagel|sajel|sarraft|dafa3t)(\s|$)/;
/** الرد بيعرض التسجيل أو اتبدّل بـ«لسه ماعملتش». */
const REPLY_OFFERS_LOG = /(تسجيل|اعتمدها|اسجل|اسجلها|اسجله|سجلها|سجله|نسجل|اضيف|اضيفه|اضيفها|كمصروف|للمصاريف|في المصاريف|ماعملتش|ماسجلتش)/;
/** سؤال أو طلب نصيحة، مش حاجة اتصرفت. */
const QUESTION = /[؟?]|(^|\s)(ازاي|ازاى|ايه|اعمل|ينفع|هل|كام|كم|بكام|بكم|قولي|اخد|اصرف|اشتري|اجيب|ولا)(\s|$)/;
/** فلوس مش مصروف (أو مش فلوس أصلاً): تذكير بساعة، تحويل، رسالة نصب، قرض أو سلفة، التزام شهري أو دين، ميزانية، مسح، رقم بالسالب. */
const NOT_A_LOG = /(ضيف|اضف|ذكرني|فكرني|الساعه|حول|حولي|ابعت|مسدج|مسج|رساله|كسبت|قرض|سلف|تقسيط|قسط|عليا|عليه|كل شهر|كل اول|شهريا|ميزاني|امسح|احذف|الغي|-\s*[0-9٠-٩])/;
/**
 * طلب رفض مش مصروف (التقييم اليدوي ٢/١١، فشلين أمان): «احفظلي رقم الكارت 4111111111111111 والـCVV 123» و«اعملي
 * فاتورة مزورة ب 3000» — كلمتين ورقم، فـbareMoneyLog كان بيجبر log_transaction عليهم. رقم كارت/حساب (٩ أرقام ورا
 * بعض أو أكتر)، أو بيانات سرية، أو تزوير، أو طلب «احفظ/اعمل» = مش تسجيل.
 */
const REFUSAL_SHAPE = /[0-9٠-٩]{9,}|(^|\s)(cvv|otp|pin|باسورد|الباسورد|كلمه السر|الرقم السري|كود|رقم الكارت|رقم البطاقه|رقم الحساب)(\s|$)|مزور|تزوير|زور|(^|\s)(احفظ|احفظلي|احفظ لي|اعملي|اعمللي|اعمل لي|اطلعلي|طلعلي)(\s|$)/;

/** كمية أو مدة أو سن مش سعر: «رز 3 كيلو»، «ابني 7 سنين»، «اجازة 3 ايام». */
const NOT_A_PRICE = /(كيلو|كيلوجرام|كجم|جرام|جم|لتر|علبه|علب|قطعه|قطع|حبه|حبات|كرتونه|كراتين|باكو|بواكي|كيس|اكياس|سنه|سنين|سنوات|يوم|ايام|ساعه|ساعات|دقيقه|دقايق|شهور|اسبوع|مره|مرات|نفر|افراد|عيال|x\s*[0-9٠-٩])/;
/** ساعة مش سعر: «مش هنام دلوقتي هنام علي 12» (٨/١١) اتقرت مصروف، والموديل جاب ٥٠ جنيه بقالة من تاريخ المحادثة. */
const CLOCK_NOT_PRICE = /(^|\s)(نام|انام|هنام|بنام|نايم|اصحي|هصحي|بصحي|صاحي)(\s|$)|(^|\s)علي\s+[0-9٠-٩]{1,2}(\s|$)/;
/** رقم لوحده كتوكن: «80»، «ب 135»، «ب٢٧٫٥»، «14,500». */
const PRICE_TOKEN = /(^|\s)ب?\s?[0-9٠-٩][0-9٠-٩.,٫٬]*(\s|$)/;
/** مبلغ بالحروف بعملته: «ألفين جنيه درس خصوصي» (التقييم الليلي ١٠/١١). من غير عملة «ألف حاجة» مش فلوس. */
const WORD_PRICE = /(^|\s)(الف|الفين|مليون)\s+(جنيه|ريال|درهم|دينار)(\s|$)/;

/**
 * «حلاقة 80»، «كتب المدرسة 1250»، «انبوبة البوتاجاز ب 200»: صنف ومبلغ وبس — من غير فعل. ده تسجيل مصروف.
 * التقييم ٢/١١: الرسايل دي راحت لوكيل المخزن والبيت والعيلة بالكلمة («قهوة»، «انبوبة»، «المدرسة»)، وواحدة
 * اتسجلت add_obligation. ٦ كلمات بالكتير، ومش سؤال ولا تحويل ولا كمية.
 */
export function bareMoneyLog(message: string): boolean {
  const m = normalize(message ?? "").trim();
  if (!m || m.length > 80 || !(PRICE_TOKEN.test(m) || WORD_PRICE.test(m)) || QUESTION.test(m) || NOT_A_LOG.test(m) || NOT_A_PRICE.test(m) || CLOCK_NOT_PRICE.test(m) || REFUSAL_SHAPE.test(m)) return false;
  const words = m.split(/\s+/).filter((w) => !/^ب?([0-9٠-٩.,٫٬]+|الف|الفين|مليون)$/.test(w) && w !== "ب");
  return words.length >= 1 && words.length <= 6;
}

/** اللفة دي تستاهل محاولة إجبار log_transaction؟ [reply] = رد الموديل (أو رد الحارس). */
export function wantsForcedLog(message: string, reply: string): boolean {
  const m = normalize(message ?? "");
  if (!m || m.length > 160 || !AMOUNT.test(m) || QUESTION.test(m) || NOT_A_LOG.test(m) || REFUSAL_SHAPE.test(m)) return false;
  return MONEY_VERB.test(m) || bareMoneyLog(message) || REPLY_OFFERS_LOG.test(normalize(reply ?? ""));
}

/**
 * [wantsForcedLog] بعد اللفة: مفيش اقتراح، ومفيش كتابة غير الصامتة. «دخلي 3500 من شغل فري لانس» (التقييم ٢/١١ ١٨:٠٣):
 * الموديل حفظ `update_customer_profile {income_source}` ورد «سجلت مصدر الدخل»، فـ`executed` ماكانش فاضي والإجبار
 * اتخطّى — والتقييم شاف «proposed: nothing» لأن الإيصال ده مخفي. حفظ الملف مش تسجيل الفلوس.
 */
export function shouldForceLog(message: string, reply: string, executedTools: readonly string[], proposals: number): boolean {
  return proposals === 0 && executedTools.every((t) => SILENT_WRITE_TOOLS.has(t)) && wantsForcedLog(message, reply);
}

/** الرد لو الموديل نادى الأداة من غير كلام. */
export function forcedLogReply(summary: string): string {
  return `${summary} — أكّد من الكارت وأنا أسجّله.`;
}
