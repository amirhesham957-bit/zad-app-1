/**
 * تنقية نص الإشعار قبل ما يترسّب في قاعدة البيانات.
 *
 * الخلفية مهمة: التطبيق سقط إذن قراءة الرسايل (`RECEIVE_SMS`) عن قصد، وبقى بيقرا رسايل
 * البنك من **إشعار** تطبيق الرسايل. يعني تطبيقات المراسلة مستثناة عمداً من قايمة التجاهل
 * في `UnifiedBankListener` — وده صح للميزة، لكنه بيفتح باب: أي رسالة شخصية فيها كلمة
 * فلوس ورقم بتعدّي البوابة، وبتتصنّف "غير واضحة"، وبيتبعت **نصها كامل** للسيرفر.
 *
 * والسيرفر كان بيخزّنه حرفياً: `zad_notification_ingest_events.title/body` بالكامل، وأول
 * ٢٠٠ حرف في `zad_insights.body` اللي بيتعرض للعميل وبيدخل سياق النموذج كمان.
 *
 * التصنيف نفسه لسه بيشتغل على النص الخام في الذاكرة — القواعد محتاجة تشوف الكلام زي ما هو.
 * اللي اتغيّر هو اللي **بيترسّب**: أي حاجة شكلها معرّف مالي أو شخصي بتتحجب قبل الكتابة.
 *
 * المبلغ **مابيتحجبش** عن قصد: هو سبب وجود الرسالة أصلاً، وبيتعرض للعميل في السؤال. اللي
 * بيتحجب هو اللي مالوش لازمة تشخيصية ولا يستاهل يترسّب — أرقام الحسابات والبطاقات
 * والآيبان والتليفونات والإيميلات.
 */

/** ١٤–٣٤ خانة أبجدرقمية بعد كود دولة = آيبان. الأول عشان أطول نمط يكسب. */
const IBAN = /\b[A-Z]{2}\d{2}[A-Z0-9]{10,30}\b/g;

/**
 * ١٣–١٩ رقم، ممكن بمسافات أو شرط بينهم = بطاقة. لازم ينتهي على **رقم** مش على فاصل:
 * `(?:\d[ -]?){13,19}` بتبلع المسافة اللي بعد آخر خانة، فـ"…3344 خصم" كانت بتطلع
 * "[بطاقة]خصم" ملزوقة. الاختبار هو اللي فضح ده.
 */
const CARD = /\b(?:\d[ -]?){12,18}\d\b/g;

/** تليفون بصيغة دولية أو محلية طويلة. */
const PHONE = /\+\d[\d\s-]{7,}\d\b/g;

/** أي سلسلة ٦ أرقام أو أكتر متصلة — رقم حساب، مرجع، رقم بطاقة مقصوص. المبالغ الحقيقية
 *  في السوق دي أقصر من كده، أو مكتوبة بفاصلة عشرية، والاتنين بيعدّوا. */
const LONG_DIGITS = /\b\d{6,}\b/g;

const EMAIL = /\b[^\s@]+@[^\s@]+\.[^\s@]+\b/g;

/**
 * بيحجب المعرّفات ويسيب باقي النص. بيرجع نص فاضي لو المدخل فاضي — مش null، عشان
 * المستدعي ما يحتاجش يفرّق.
 */
export function redactNotificationText(raw: string | null | undefined): string {
  if (!raw) return "";
  return raw
    .replace(IBAN, "[حساب]")
    .replace(CARD, "[بطاقة]")
    .replace(PHONE, "[تليفون]")
    .replace(EMAIL, "[بريد]")
    .replace(LONG_DIGITS, "[رقم]");
}

/** ٨ أرقام أو أكتر متصلة: حساب أو مرجع. المبالغ لحد ٩٬٩٩٩٬٩٩٩ من غير فاصلة بتعدّي. */
const ACCOUNT_DIGITS = /\b\d{8,}\b/g;

/**
 * النص اللي بيتبعت لموديل البوابة (ZAD_PLAN ٨.٢، أقل داتا ممكنة): نفس حجب الآيبان والبطاقة
 * والتليفون والبريد، بس الأرقام الطويلة من ٨ مش من ٦ — الموديل لازم يقرا المبلغ، و«تم إيداع 125000
 * جنيه» كانت هتطلع «[رقم] جنيه» برّه. آخر ٤ أرقام من الكارت (****1234) بيفضلوا عشان مطابقة الكارت.
 */
export function redactForModel(raw: string | null | undefined): string {
  if (!raw) return "";
  return raw
    .replace(IBAN, "[حساب]")
    .replace(CARD, "[بطاقة]")
    .replace(PHONE, "[تليفون]")
    .replace(EMAIL, "[بريد]")
    .replace(ACCOUNT_DIGITS, "[رقم]");
}
