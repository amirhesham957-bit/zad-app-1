/**
 * بلوك SOUL الكامل — سطر واحد لكل فقرة عشان يتلقف صح مع البرومبتات العربية. `voice` =
 * `customer.zad_voice` من السناب شوت (أو الصف)؛ أي حاجة غير male = صوت بنت.
 * empty-safe: بيرجع "" لو المصفوفة فاضية (نفس نمط lessonsBlock).
 */
export function soulBlock(voice?: unknown): string {
  const soul = zadVoiceGender(voice) === "male" ? ZAD_SOUL_MALE : ZAD_SOUL;
  if (!soul.length) return "";
  return "\n=== SOUL — هويتك ===\n"
    + soul.map((s) => "- " + s).join("\n")
    + "\n=== نهاية الهوية ===\n";
}
