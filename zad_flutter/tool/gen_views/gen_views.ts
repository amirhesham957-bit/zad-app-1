// P1.4: generates lib/core/generated/zad_views.g.dart from the zad_view_* RPCs in
// supabase/migrations/20261127140000_view_rpcs.sql.
//   deno run -A tool/gen_views/gen_views.ts            # write the file
//   deno run -A tool/gen_views/gen_views.ts --check    # exit 1 if the stored file differs
// Exits non-zero on an action id that is not in allowed_actions.json.

export const VIEWS = ["home", "money", "house", "family"] as const;
export type ViewName = (typeof VIEWS)[number];

export interface ViewSpec {
  name: ViewName;
  numbers: { key: string; source: string }[];
  hasThreat: boolean;
  hasNextAppointment: boolean;
  actions: string[];
}

export function parseViews(sql: string): ViewSpec[] {
  const out: ViewSpec[] = [];
  for (const name of VIEWS) {
    const re = new RegExp(
      `create or replace function public\\.zad_view_${name}\\([^)]*\\)[\\s\\S]*?\\nend \\$\\$;`,
    );
    const body = sql.match(re)?.[0];
    if (!body) throw new Error(`zad_view_${name} not found in migration`);
    const numbers: { key: string; source: string }[] = [];
    const seen = new Set<string>();
    // 'key', public.zad_view_num(<expr>, 'source')   |   'key', v_x -> 'numbers' -> 'key'
    const numRe =
      /'(\w+)',\s*(?:public\.zad_view_num\((?:[^'()]|\([^()]*\))*?,\s*'([^']+)'\)|(v_\w+) -> 'numbers' -> '(\w+)')/g;
    for (const m of body.matchAll(numRe)) {
      const key = m[1];
      let source = m[2];
      if (!source) {
        // home reuses money/house numbers: take the source from there.
        const from = m[3] === "v_money" ? "money" : "house";
        const ref = m[4];
        const other = sql.match(
          new RegExp(
            `function public\\.zad_view_${from}\\([^)]*\\)[\\s\\S]*?\\nend \\$\\$;`,
          ),
        )?.[0] ?? "";
        source = other.match(
          new RegExp(`'${ref}',\\s*public\\.zad_view_num\\([^\\n]*?,\\s*'([^']+)'\\)`),
        )?.[1] ?? "";
        if (!source) throw new Error(`cannot resolve source of ${name}.${key}`);
      }
      if (seen.has(key)) continue;
      seen.add(key);
      numbers.push({ key, source });
    }
    if (numbers.length === 0) throw new Error(`zad_view_${name}: no numbers found`);
    const actions = [...new Set([...body.matchAll(/'id',\s*'(\w+)'/g)].map((m) => m[1]))];
    out.push({
      name,
      numbers,
      hasThreat: /'threat',\s*(jsonb_build_object|v_money -> 'threat')/.test(body),
      hasNextAppointment: /'next_appointment'/.test(body),
      actions,
    });
  }
  return out;
}

export function checkActions(specs: ViewSpec[], allowed: string[]): string[] {
  const ok = new Set(allowed);
  const bad: string[] = [];
  for (const s of specs) for (const a of s.actions) if (!ok.has(a)) bad.push(`${s.name}: ${a}`);
  return bad;
}

const camel = (s: string) => s.replace(/_(\w)/g, (_, c) => c.toUpperCase());
const pascal = (s: string) => camel(s[0].toUpperCase() + s.slice(1));

export function render(specs: ViewSpec[], allowed: string[]): string {
  const L: string[] = [];
  L.push(
    "// GENERATED by tool/gen_views/gen_views.ts from supabase/migrations/20261127140000_view_rpcs.sql.",
    "// Do not edit. Regenerate: deno run -A tool/gen_views/gen_views.ts",
    "// ignore_for_file: type=lint",
    "",
    "/// A number from a zad_view_* RPC: the value and where it came from.",
    "class ViewNumber {",
    "  const ViewNumber({required this.value, required this.source});",
    "  factory ViewNumber.fromJson(Map<String, dynamic> j) =>",
    "      ViewNumber(value: (j['value'] as num?)?.toDouble(), source: j['source'] as String? ?? '');",
    "  final double? value;",
    "  final String source;",
    "}",
    "",
    "/// A text value (e.g. threat) with its source.",
    "class ViewText {",
    "  const ViewText({required this.value, required this.source});",
    "  factory ViewText.fromJson(Map<String, dynamic> j) =>",
    "      ViewText(value: j['value'] as String?, source: j['source'] as String? ?? '');",
    "  final String? value;",
    "  final String source;",
    "}",
    "",
    "/// The next upcoming appointment, as returned by home/house.",
    "class ViewNextAppointment {",
    "  const ViewNextAppointment({required this.title, required this.startsAt});",
    "  factory ViewNextAppointment.fromJson(Map<String, dynamic> j) => ViewNextAppointment(",
    "      title: j['title'] as String?, startsAt: DateTime.tryParse('${j['starts_at']}'));",
    "  final String? title;",
    "  final DateTime? startsAt;",
    "}",
    "",
    "/// Approved available_actions ids (allowed_actions.json). Unknown ids parse to null.",
    "enum ZadViewAction {",
    ...allowed.map((a, i) => `  ${camel(a)}('${a}')${i === allowed.length - 1 ? ";" : ","}`),
    "  const ZadViewAction(this.id);",
    "  final String id;",
    "  static ZadViewAction? parse(String? id) {",
    "    for (final a in values) {",
    "      if (a.id == id) return a;",
    "    }",
    "    return null;",
    "  }",
    "}",
    "",
    "/// One entry of available_actions.",
    "class ViewAction {",
    "  const ViewAction({required this.id, required this.label});",
    "  factory ViewAction.fromJson(Map<String, dynamic> j) =>",
    "      ViewAction(id: ZadViewAction.parse(j['id'] as String?), label: j['label'] as String? ?? '');",
    "  final ZadViewAction? id;",
    "  final String label;",
    "}",
    "",
    "List<ViewAction> _actions(dynamic v) => ((v as List?) ?? const [])",
    "    .map((e) => ViewAction.fromJson(Map<String, dynamic>.from(e as Map)))",
    "    .toList();",
    "",
    "ViewNumber? _num(Map<String, dynamic> n, String k) =>",
    "    n[k] is Map ? ViewNumber.fromJson(Map<String, dynamic>.from(n[k] as Map)) : null;",
    "",
  );
  for (const s of specs) {
    const C = `Zad${pascal(s.name)}View`;
    // family numbers are conditional on consent, so every number is nullable there.
    L.push(`/// zad_view_${s.name}. Number sources: ${s.numbers.map((n) => `${n.key}=${n.source}`).join(", ")}.`);
    L.push(`class ${C} {`);
    L.push(`  const ${C}({`);
    for (const n of s.numbers) L.push(`    this.${camel(n.key)},`);
    if (s.hasThreat) L.push("    this.threat,");
    if (s.hasNextAppointment) L.push("    this.nextAppointment,");
    L.push("    this.availableActions = const [],");
    L.push("  });");
    L.push(`  factory ${C}.fromJson(Map<String, dynamic> j) {`);
    L.push("    final n = Map<String, dynamic>.from((j['numbers'] as Map?) ?? const {});");
    L.push(`    return ${C}(`);
    for (const n of s.numbers) L.push(`      ${camel(n.key)}: _num(n, '${n.key}'),`);
    if (s.hasThreat) {
      L.push("      threat: j['threat'] is Map ? ViewText.fromJson(Map<String, dynamic>.from(j['threat'] as Map)) : null,");
    }
    if (s.hasNextAppointment) {
      L.push("      nextAppointment: j['next_appointment'] is Map");
      L.push("          ? ViewNextAppointment.fromJson(Map<String, dynamic>.from(j['next_appointment'] as Map))");
      L.push("          : null,");
    }
    L.push("      availableActions: _actions(j['available_actions']),");
    L.push("    );");
    L.push("  }");
    for (const n of s.numbers) L.push(`  final ViewNumber? ${camel(n.key)};`);
    if (s.hasThreat) L.push("  final ViewText? threat;");
    if (s.hasNextAppointment) L.push("  final ViewNextAppointment? nextAppointment;");
    L.push("  final List<ViewAction> availableActions;");
    L.push("}", "");
  }
  return L.join("\n");
}

async function main() {
  const root = new URL("../../", import.meta.url); // zad_flutter/
  const sqlPath = new URL("../supabase/migrations/20261127140000_view_rpcs.sql", root);
  const allowPath = new URL("allowed_actions.json", import.meta.url);
  const outPath = new URL("lib/core/generated/zad_views.g.dart", root);
  const sql = await Deno.readTextFile(sqlPath);
  const allowed: string[] = JSON.parse(await Deno.readTextFile(allowPath)).actions;
  const specs = parseViews(sql);
  const bad = checkActions(specs, allowed);
  if (bad.length) {
    console.error(`gen_views: action ids not in allowed_actions.json:\n  ${bad.join("\n  ")}`);
    Deno.exit(1);
  }
  const text = render(specs, allowed);
  if (Deno.args.includes("--check")) {
    let cur = "";
    try { cur = await Deno.readTextFile(outPath); } catch { /* missing */ }
    if (cur !== text) {
      console.error("gen_views: zad_views.g.dart is stale. Run: deno run -A tool/gen_views/gen_views.ts");
      Deno.exit(1);
    }
    console.log("gen_views: up to date");
    return;
  }
  await Deno.mkdir(new URL("lib/core/generated/", root), { recursive: true });
  await Deno.writeTextFile(outPath, text);
  console.log(`gen_views: wrote ${outPath.pathname}`);
}
if (import.meta.main) await main();
